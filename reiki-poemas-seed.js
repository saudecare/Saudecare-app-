async function seedReikiPoemas(){
  try {
    const existentes = await getDocs(collection(db, 'tenants', REIKI_TENANT, 'reikiPoems'));
    if (!existentes.empty){
      alert('Já existem ' + existentes.size + ' poemas guardados.\n\nSeed cancelado para não duplicar.');
      return;
    }
    let n = 0;
    for (const x of POEMAS){
      await addDoc(collection(db, 'tenants', REIKI_TENANT, 'reikiPoems'), {
        numero: x.n, titulo: x.t || '', japones: x.jp || '', texto: x.p || '',
        principio: x.g || '', interpretacao: x.i || '',
        criadoEm: new Date().toISOString()
      });
      n++;
    }
    alert('Carregados os ' + n + ' poemas da versão Hikari Fafe.');
  } catch(err){
    console.error('[Poemas] Erro:', err);
    alert('Erro ao carregar: ' + err.message);
  }
}

window.seedReikiPoemas = seedReikiPoemas;
window.POEMAS_HIKARI = POEMAS;
